# executed inside the lib src dir
function build() {
    LIBS_ROOT=$(realpath $LIBS_DIR)
    if [ "$TYPE" == "msys2" ]; then

        MINGW_PREFIX="${MINGW_PREFIX:-/mingw64}"
        LIBXML2_ROOT="$MINGW_PREFIX"
        LIBXML2_INCLUDE_DIR="$LIBXML2_ROOT/include/libxml2"
        LIBXML2_LIBRARY="$LIBXML2_ROOT/lib/libxml2.a"

        mkdir -p "build_${TYPE}_${ARCH}"
        cd "build_${TYPE}_${ARCH}"
        DEFINES="-DLIBRARY_SUFFIX=${ARCH} \
	        -DCMAKE_BUILD_TYPE=Release \
	        -DCMAKE_C_STANDARD=${C_STANDARD} \
	        -DCMAKE_CXX_STANDARD=${CPP_STANDARD} \
	        -DCMAKE_CXX_STANDARD_REQUIRED=ON \
	        -DCMAKE_CXX_EXTENSIONS=OFF
	        -DBUILD_SHARED_LIBS=OFF \
	        -DCMAKE_INSTALL_PREFIX=Release \
	        -DCMAKE_INCLUDE_OUTPUT_DIRECTORY=include \
	        -DCMAKE_INSTALL_INCLUDEDIR=include"
        cmake .. ${DEFINES} \
            -DCMAKE_CXX_FLAGS="-DUSE_PTHREADS=1 -Iinclude" \
            -DCMAKE_C_FLAGS="-DUSE_PTHREADS=1 -Iinclude -Wno-implicit-function-declaration" \
            -DCMAKE_BUILD_TYPE=Release \
            -DCMAKE_INSTALL_LIBDIR="lib" \
            -DDO_XML_INSTALL=ON \
            -DCMAKE_SYSTEM_NAME=$TYPE \
            -DCMAKE_SYSTEM_PROCESSOR=$ABI \
            -DLIBXML2_ROOT=$LIBXML2_ROOT \
            -DLIBXML2_INCLUDE_DIR=$LIBXML2_INCLUDE_DIR \
            -DLIBXML2_LIBRARY=$LIBXML2_LIBRARY
        cmake --build . --config Release -j${PARALLEL_MAKE}
        cd ..
